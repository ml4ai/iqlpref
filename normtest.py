#!/usr/bin/env python
"""normtest.py -- the normalization test's IQL sweep files (gp_reward-priors HANDOFF §14.104, as
amended by §14.108).  Which normalization rule the replication uses: two fixed rules (N: index 0,
F: index 2; O3 if both fail) against the selected process S, fixed before any of its runs.

Every file: the reward shift (iql_eval's default gauge_reward max0 for a learned reward),
return_range_split "length" (leak-free, §14.83), Study 1's reward models 0-10 reused on NEW IQL
seeds via reward_model_seed_offset 50 (IQL seed s loads model s - 50).  MR, PT, NMR and the
averaging MR ensemble; all four datasets; full data; BOTH protocols (§14.108: the rule is chosen
on both, and one rule must pass under each).

  GRIDS   norm_sweeps/grid_{std,cand}_antmaze_<v>_<fam>     seed 50 (model 0), indices 0-7: S's
          selection unit, scored by Study 1's stage-4 rule (`normtest.py winners`)
  CELLS   norm_sweeps/eval_{std,cand}_antmaze_<v>_<fam>_idx<k>  seeds 51-60 (models 1-10), one per
          index an arm needs: 0 (N), 2 (F), S's grid winner, and O3's per-(protocol, dataset)
          index if O3 is run (`write --o3`).  An arm whose index another arm already has shares
          that cell -- the same reward model, IQL seed and index, so the same runs.
  FLOOR   norm_sweeps/zero_{std,cand}_antmaze_<v>        the zero reward, index 0, seeds 51-60
          (§14.108's floor on criterion (ii))

Each file is Study 1's anchor (or trivial) cell plus exactly: return_range_split, the offset (a
learned reward), the seeds -- checked on the rendered text.  Every file carries
return_range_split; a learned-reward file also the offset, which no other spec has.  The zero
files equal the replication's zero cells but for the seeds (51-60 vs 101-110); every collector
checks seeds.

    python normtest.py write [--write] [--o3]
    python normtest.py winners [--write]        # S's grid winners, then O3's indices
    python normtest.py --selftest
Launch with stage4_queue.sh items  norm:<file>@normtest  (one sweep each; norm_sweeps/launch.sh).
"""

import argparse
import json
import os
import sys

import yaml

import phase2_sweeps as P

ROOT = P.ROOT
DIR = "norm_sweeps"
GRID_SEED = 50
EVAL_SEEDS = list(range(51, 61))
OFFSET = 50
SPLIT = "length"
PROTOCOLS = ("std", "cand")
ANCHORS = {"mr": "mr_sweeps/sweep_antmaze_{v}", "pt": "pt_sweeps/sweep_antmaze_{v}",
           "nmr": "nmr_sweeps/sweep_antmaze_{v}", "ens_mean": "ensemble_sweeps/sweep_antmaze_{v}_mean"}
METHOD = {"mr": "MR", "pt": "PT", "nmr": "NMR", "ens_mean": "ENS_MEAN"}
ARM_INDEX = {"N": 0, "F": 2}
WINNERS = os.path.join("results", "normtest_grid_winners.json")
MARK = "Lineage: NORMTEST"


def family_fixed(sp, fam, v, prot):
    f = dict(sp[ANCHORS[fam].format(v=v)], return_range_split=SPLIT, reward_model_seed_offset=OFFSET)
    if prot == "cand":
        f["drop_terminals"] = True
    return f


def zero_fixed(sp, v, prot):
    f = {"config_path": sp[f"tr_sweeps/sweep_antmaze_{v}"]["config_path"], "trivial_reward": "zero",
         "return_range_split": SPLIT}
    if prot == "cand":
        f["drop_terminals"] = True
    return f


def grid_name(v, fam, prot):
    return f"{DIR}/grid_{prot}_antmaze_{v}_{fam}"


def cell_name(v, fam, prot, k):
    return f"{DIR}/eval_{prot}_antmaze_{v}_{fam}_idx{k}"


def zero_name(v, prot):
    return f"{DIR}/zero_{prot}_antmaze_{v}"


def o3_key(v, prot):
    return f"o3_{prot}_{v}"


def arm_indices(fam, v, prot, gwin, o3=False):
    """{arm: index or None} for one (family, dataset, protocol)."""
    out = dict(ARM_INDEX)
    out["S"] = gwin.get(grid_name(v, fam, prot))
    if o3:
        out["O3"] = gwin.get(o3_key(v, prot))
    return out


def render(name, fixed, seeds, index, what):
    lin = (f"{MARK} grid, seed {GRID_SEED} (reward model 0), normalize_reward {index} (S's selection)."
           if isinstance(index, list) else
           f"{MARK} eval, seeds {seeds[0]}-{seeds[-1]} (reward models {seeds[0] - OFFSET}-{seeds[-1] - OFFSET}), "
           f"normalize_reward {index}.")
    head = ["# GENERATED by normtest.py -- do not hand-edit; regenerate instead",
            f"# (gp_reward-priors HANDOFF §14.104, §14.108).  {lin}",
            f"# {what}.  return_range_split {SPLIT!r} (leak-free).  Study 1's reward models, new IQL seeds."]
    p = dict(fixed)
    p["seed"] = {"value": seeds} if isinstance(seeds, int) else {"values": seeds}
    p["normalize_reward"] = {"values": index} if isinstance(index, list) else {"value": index}
    params = {k: (x if isinstance(x, dict) else {"value": x}) for k, x in p.items()}
    doc = {"project": P.IQL_PROJECT, "program": P.DEFAULT_PROGRAM, "method": "grid", "parameters": params}
    return "\n".join(head) + "\n" + yaml.safe_dump(doc, sort_keys=False)


def check(sp, text, base, learned, prot, seeds, index):
    doc = yaml.safe_load(text)
    got = P.flat(doc["parameters"])
    extra = {"return_range_split"} | ({"reward_model_seed_offset"} if learned else set())
    want = dict(base, return_range_split=SPLIT, **({"reward_model_seed_offset": OFFSET} if learned else {}))
    if prot == "cand":
        want["drop_terminals"] = True
    probs = []
    diff = {k for k in set(got) | set(want) if got.get(k) != want.get(k)} - {"seed", "normalize_reward"}
    if diff:
        probs.append(f"params differ from the spec in {sorted(diff)}")
    if not extra <= set(got):
        probs.append(f"missing {sorted(extra - set(got))}")
    if got.get("seed") != seeds or got.get("normalize_reward") != index:
        probs.append(f"seed {got.get('seed')} index {got.get('normalize_reward')}")
    if doc["program"] != P.DEFAULT_PROGRAM or MARK not in text:
        probs.append("program or lineage mark")
    if (prot == "cand") != (got.get("drop_terminals") is True):
        probs.append(f"drop_terminals {got.get('drop_terminals')!r} under {prot}")
    return probs


def plan(sp, gwin, o3=False):
    """[(name, text-maker args, skip reason or None)] for every file."""
    out = []
    for v in P.VARIANTS:
        for prot in PROTOCOLS:
            for fam in ANCHORS:
                fx = family_fixed(sp, fam, v, prot)
                base = sp[ANCHORS[fam].format(v=v)]
                out.append((grid_name(v, fam, prot), (fx, GRID_SEED, list(P.STAGE4_INDICES),
                            f"{METHOD[fam]}, {prot}, S's grid"), (base, True, prot), None))
                ks = {}
                for arm, k in arm_indices(fam, v, prot, gwin, o3).items():
                    if k is None:
                        out.append((f"{cell_name(v, fam, prot, '?')} ({arm})", None, None,
                                    f"{arm}: no index yet (grid not scored)"))
                        continue
                    ks.setdefault(k, []).append(arm)
                for k, arms in sorted(ks.items()):
                    out.append((cell_name(v, fam, prot, k), (fx, EVAL_SEEDS, k,
                                f"{METHOD[fam]}, {prot}, arm(s) {'/'.join(arms)}"), (base, True, prot), None))
            out.append((zero_name(v, prot), (zero_fixed(sp, v, prot), EVAL_SEEDS, 0, f"zero reward, {prot} (the floor)"),
                        ({"config_path": sp[f"tr_sweeps/sweep_antmaze_{v}"]["config_path"], "trivial_reward": "zero"},
                         False, prot), None))
    return out


def cmd_write(do_write, o3=False, root=ROOT):
    sp = P.spec()
    path = os.path.join(root, WINNERS)
    gwin = json.load(open(path)) if os.path.exists(path) else {}
    n = skipped = bad = 0
    for name, args, chk, why in plan(sp, gwin, o3):
        if why:
            skipped += 1
            continue
        fixed, seeds, index, what = args
        text = render(name, fixed, seeds, index, what)
        probs = check(sp, text, chk[0], chk[1], chk[2], seeds, index)
        if probs:
            bad += 1
            print(f"  !! {name}: {'; '.join(probs)}")
            continue
        fpath = os.path.join(root, name + ".yaml")
        old = open(fpath).read() if os.path.exists(fpath) else ""
        change = "unchanged" if old == text else ("CHANGED" if old else "new")
        if do_write and old != text:
            os.makedirs(os.path.dirname(fpath), exist_ok=True)
            open(fpath, "w").write(text)
        n += 1
        print(f"  {name:58s} {change}{' (written)' if do_write and old != text else ''}")
    print(f"\n  {n} file(s) {'written' if do_write else 'checked (dry run; --write to apply)'}; "
          f"{skipped} waiting on S's grid winners{'' if o3 else ' (O3 not requested)'}; {bad} FAILED")
    return 1 if bad else 0


def o3_index(scores_by_family):
    """{family: {index: score}} for one (protocol, dataset) -> the index with the highest mean score
    over the families, exact ties to the lowest index (§14.104's O3 rule)."""
    idx = sorted(set.intersection(*(set(s) for s in scores_by_family.values())))
    means = {k: sum(s[k] for s in scores_by_family.values()) / len(scores_by_family) for k in idx}
    best = max(means.values())
    return min(k for k in idx if means[k] == best)


def cmd_winners(do_write):
    sys.path.insert(0, os.path.join(ROOT, "results"))
    import iql_score
    import wandb
    api = wandb.Api(timeout=120)
    sp = P.spec()
    path = os.path.join(ROOT, WINNERS)
    gwin = json.load(open(path)) if os.path.exists(path) else {}
    fixed_of = {grid_name(v, fam, prot): family_fixed(sp, fam, v, prot)
                for v in P.VARIANTS for prot in PROTOCOLS for fam in ANCHORS}
    found = {}
    for sw in P.iql_sweeps(api):
        params = sw.config.get("parameters")
        hits = P.match_entry(params, fixed_of)
        flat = P.flat(params)
        if len(hits) == 1 and flat.get("seed") == GRID_SEED and flat.get("normalize_reward") == list(P.STAGE4_INDICES):
            found.setdefault(hits[0], []).append(sw)
    new, by = dict(gwin), {}
    for name in fixed_of:
        sws = found.get(name, [])
        if len(sws) != 1:
            print(f"  {name:48s} {'no sweep' if not sws else f'{len(sws)} sweeps -- NOT read'}")
            continue
        runs = []
        for r in sws[0].runs:
            cfg = r.config or {}
            m = cfg.get("reward_model_path", "")
            if not str(m).endswith("_0") or cfg.get("return_range_split") != SPLIT:
                print(f"  {name:48s} run {r.id}: model {m!r}, split {cfg.get('return_range_split')!r} -- NOT read")
                runs = None
                break
            runs.append(iql_score.score_run(r))
        if runs is None:
            continue
        try:
            win, table = iql_score.select_normalization(runs, list(P.STAGE4_INDICES))
        except ValueError as e:
            print(f"  {name:48s} {sws[0].id}  INCOMPLETE: {e}")
            continue
        if name in gwin and gwin[name] != int(win):
            sys.exit(f"!! {name}: winner changed {gwin[name]} -> {win}: nothing written")
        new[name] = int(win)
        by[name] = {s["normalize_reward"]: s["score"] for s in table}
        print(f"  {name:48s} {sws[0].id}  " + " ".join(f"{by[name][i]:.3f}" for i in P.STAGE4_INDICES) + f"   winner {win}")
    for v in P.VARIANTS:                                # O3: needs all four families' grids
        for prot in PROTOCOLS:
            names = [grid_name(v, fam, prot) for fam in ANCHORS]
            if all(n in by for n in names):
                k = o3_index({n: by[n] for n in names})
                if o3_key(v, prot) in gwin and gwin[o3_key(v, prot)] != k:
                    sys.exit(f"!! {o3_key(v, prot)} changed {gwin[o3_key(v, prot)]} -> {k}: nothing written")
                new[o3_key(v, prot)] = k
                print(f"  {o3_key(v, prot):48s} O3 index {k}")
    if do_write:
        json.dump(dict(sorted(new.items())), open(path, "w"), indent=1)
        print(f"\n  {len(new)} entries in {WINNERS}")
    return 0


def selftest():
    import tempfile
    sp = P.spec()
    pl = plan(sp, {})
    writable = [x for x in pl if x[3] is None]
    assert len([x for x in writable if "/grid_" in x[0]]) == 32                    # 4 fam x 4 v x 2 prot
    assert len([x for x in writable if "/eval_" in x[0]]) == 64                    # N and F, before S is scored
    assert len([x for x in writable if "/zero_" in x[0]]) == 8
    for name, args, chk, _ in writable:
        fixed, seeds, index, what = args
        assert not check(sp, render(name, fixed, seeds, index, what), chk[0], chk[1], chk[2], seeds, index), name
    # S's winner equal to N's index shares N's cell; a different one adds a cell
    g = {grid_name("large_play", "mr", "cand"): 0, grid_name("large_play", "pt", "cand"): 6}
    pl = {x[0]: x for x in plan(sp, g) if x[3] is None}
    assert "N/S" in pl[cell_name("large_play", "mr", "cand", 0)][1][3]
    assert cell_name("large_play", "pt", "cand", 6) in pl and "S" in pl[cell_name("large_play", "pt", "cand", 6)][1][3]
    # never a Study 1, replication or leak-control cell
    import replication as Y
    E = P._conditions()
    others = [sp, P.noterm_spec(sp), P.trivial_spec(sp), {n: f for n, (_, f, _) in P.control_spec(sp).items()},
              {n: c["fixed"] for n, c in Y.cell_spec(sp, E).items() if not c["fam"].startswith("trivial")},
              {n: g["fixed"] for n, g in Y.grid_spec(sp, E).items()}]
    lf = P.leakfree_spec()
    others.append({k: f for k, (_, f, _, _, _) in lf.items()})
    for name, args, _, _ in writable:
        if "/zero_" in name:
            continue
        params = yaml.safe_load(render(name, *args))["parameters"]
        for o in others:
            assert not P.match_entry(params, o), (name, P.match_entry(params, o))
    # the zero cells equal the replication's but for the seeds (the collectors' seed checks keep them apart)
    zr = {n: c["fixed"] for n, c in Y.cell_spec(sp, E).items() if c["fam"] == "trivial_zero"}
    zp = yaml.safe_load(render(zero_name("medium_play", "cand"), zero_fixed(sp, "medium_play", "cand"), EVAL_SEEDS, 0, "z"))["parameters"]
    assert P.match_entry(zp, zr) == [f"{Y.REPL_DIR}/cand_zero_antmaze_medium_play"] and P.flat(zp)["seed"] == EVAL_SEEDS
    # O3: the highest mean over families, ties to the lowest index
    assert o3_index({"a": {0: .1, 1: .3, 2: .3}, "b": {0: .2, 1: .1, 2: .1}}) == 1
    assert o3_index({"a": {0: .2, 1: .1}, "b": {0: .0, 1: .1}}) == 0             # exact tie -> lowest
    with tempfile.TemporaryDirectory() as d:
        assert cmd_write(True, root=d) == 0
        assert len([f for f in os.listdir(os.path.join(d, DIR))]) == 32 + 64 + 8
    print("selftest OK")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", nargs="?", choices=("write", "winners"))
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--o3", action="store_true", help="also O3's cells (only once N and F have both failed)")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if a.cmd == "write":
        return cmd_write(a.write, a.o3)
    if a.cmd == "winners":
        return cmd_winners(a.write)
    ap.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
